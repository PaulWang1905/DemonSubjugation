// ---------------------------------------------------------------------------
// battle sprites (PIC 3-n, 12 frames: idle, attack x4, cast x3, guard, hit,
// weak, knocked out) and portraits (PIC 1-n)

function battleFrames(base: Pix, weapon: (p: Pix, k: number) => void, castProp: (p: Pix, k: number) => void): Pix[] {
  const Wd = 26;
  const H = 30;
  const at = (dx: number, dy: number) => new Pix(Wd, H).blit(base, 1 + dx, 5 + dy);
  const idle = at(0, 0);
  weapon(idle, 0);
  const attack = [1, 2, 3, 4].map((k) => {
    const p = at(-k, 0);
    weapon(p, k);
    return p;
  });
  const cast = [0, 1, 2].map((k) => {
    const p = at(0, 0);
    castProp(p, k);
    return p;
  });
  const guard = at(1, 1);
  guard.fill(2, 13, 5, 11, W).rect(2, 13, 5, 11, B).line(4, 14, 4, 22, B);
  const hit = at(3, 0);
  hit.invert(9, 5, 9, 8);
  const weak = at(0, 3);
  const ko = new Pix(Wd, H).art(["    ######  ############  ", "   #......##............# ", "   #.####.##.........#### ", "    ######  ############  "], 0, 22);
  return [idle, ...attack, ...cast, guard, hit, weak, ko];
}

export function rinBattle(): Pix[] {
  const base = Pix.fromArt([
    "         ######         ", "        #.#.#..#        ", "       ##########       ", "       #.#....#.#       ", "       #.#.#..#.#       ",
    "       #..#..#..#       ", "        #..##..#        ", "       ##########       ", "      #.#......#.#      ", "     #..#......#..#     ",
    "     #.##......##.#     ", "      ##........##      ", "       #........#       ", "       #........#       ", "      #..........#      ",
    "      ############      ", "        #.#  #.#        ", "        #.#  #.#        ", "        #.#  #.#        ", "       ###    ###       ",
  ]);
  return battleFrames(
    base,
    (p, k) => {
      // a ringing rod, swung forward as k grows
      if (k === 0) p.line(4, 2, 4, 20).set(3, 2, B).set(5, 2, B).set(4, 1, B);
      else p.line(5 - k, 14, 0, 14 - k * 3).line(6 - k, 14, 1, 14 - k * 3);
    },
    (p, k) => {
      p.line(19, 13, 22, 4 - k).art([" ## ", "#..#", " ## "], 20, 1 - k);
      if (k > 0) p.set(16, 1, B).set(24, 2, B).set(19, 0, B);
    },
  );
}

