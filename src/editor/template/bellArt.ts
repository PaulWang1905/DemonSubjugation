export function forestBackground(): Pix {
  const bg = new Pix(160, 96, W);
  for (let i = 0; i < 9; i++) {
    const x = 6 + i * 19 + ((i * 7) % 5);
    const h = 18 + ((i * 13) % 9);
    for (let y = 0; y < h; y++) bg.line(x - Math.floor(y / 2), 36 - h + y, x + Math.floor(y / 2), 36 - h + y, B);
    bg.line(x, 36, x, 40, B);
  }
  bg.line(0, 41, 159, 41, B);
  for (let y = 48; y < 96; y += 8) for (let x = (y * 5) % 13; x < 160; x += 13) bg.art(["#.#", ".#."], x, y);
  return bg;
}
export function caveBackground(): Pix {
  const bg = new Pix(160, 96, W);
  for (let x = 0; x < 160; x += 12) {
    const len = 6 + ((x * 7) % 11);
    for (let y = 0; y < len; y++) bg.line(x + Math.floor(y / 3), y, x + 8 - Math.floor(y / 3), y, B);
  }
  for (let x = 0; x < 160; x++) bg.set(x, 44 + Math.round(2 * Math.sin(x / 7)), B);
  for (let y = 52; y < 96; y += 9) for (let x = (y * 3) % 17; x < 160; x += 17) bg.art([".##.", "#..#", ".##."], x, y);
  return bg;
}
export function marshBackground(): Pix {
  const bg = new Pix(160, 96, W);
  for (let x = 0; x < 160; x += 5) {
    const h = 6 + ((x * 11) % 9);
    bg.line(x, 40, x + ((x / 5) % 2 ? 1 : -1), 40 - h, B);
  }
  for (let x = 0; x < 160; x++) bg.set(x, 40, B);
  for (let y = 50; y < 96; y += 6) for (let x = (y * 7) % 19; x < 160; x += 19) bg.line(x, y, x + 6, y, B);
  return bg;
}
export function towerBackground(): Pix {
  const bg = new Pix(160, 96, W);
  for (let y = 0; y < 44; y += 8) {
    bg.line(0, y, 159, y, B);
    for (let x = (y / 8) % 2 ? 0 : 10; x < 160; x += 20) bg.line(x, y, x, y + 8, B);
  }
  bg.line(0, 44, 159, 44, B).line(0, 45, 159, 45, B);
  for (let y = 54; y < 96; y += 10) bg.line(0, y, 159, y, B);
  return bg;
}
