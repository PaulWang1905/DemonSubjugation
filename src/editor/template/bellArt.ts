export function slash(index: number): LibEntry {
  const s = (rows: string[]) => Pix.fromArt(rows).frame();
  return {
    resType: 5, type: 2, index,
    data: encodeSrs(2, index, [
      { x: 10, y: 0, show: 3, next: 2, image: 0 }, { x: 4, y: 4, show: 3, next: 2, image: 1 }, { x: 0, y: 8, show: 3, next: 3, image: 2 }, { x: 0, y: 8, show: 2, next: 2, image: 3 },
    ], [
      s(["      #", "     # ", "    #  ", "   #   "]),
      s(["         #", "        # ", "      ##  ", "    ##    ", "   #      ", " ##       "]),
      s(["            ##", "          ##  ", "        ##    ", "      ##      ", "    ##        ", "  ##          ", "##            "]),
      s(["#   #   #   #", " # # # # # # ", "  #   #   #  "]),
    ]),
  };
}

export function wave(index: number): LibEntry {
  const w = (n: number) => {
    const p = new Pix(32, 12);
    for (let x = 0; x < 32; x++) {
      p.set(x, 5 + Math.round(3 * Math.sin((x + n * 4) / 3)), B);
      if (n > 0) p.set(x, 5 + Math.round(3 * Math.sin((x + n * 4) / 3 + 2)), B);
    }
    return p.frame();
  };
  return {
    resType: 5, type: 2, index,
    data: encodeSrs(2, index, [
      { x: -8, y: 0, show: 3, next: 2, image: 0 }, { x: -4, y: 2, show: 3, next: 2, image: 1 }, { x: 0, y: 4, show: 3, next: 2, image: 2 }, { x: 0, y: 4, show: 3, next: 3, image: 1 },
    ], [w(0), w(1), w(2)]),
  };
}
