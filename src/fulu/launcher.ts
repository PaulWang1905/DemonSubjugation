/** The launcher's state into `ram`. */
export function launcherRam(ram: Uint8Array): void {
  for (const r of LAUNCHER_RAM) {
    if (r.length === 3) ram.fill(r[2], r[0], r[0] + r[1]);
    else ram.set(r[1], r[0]);
  }
}
