// word, the year, the screen's and the file code's settings...).
//
// Measured by starting nine programs on the firmware (one of them with
// another program before it in the flash) and keeping the bytes that were the
// same each time. Left out: what differs from program to program (the
// launcher's own list at $2088-$20AE and file code scratch), the launcher's
